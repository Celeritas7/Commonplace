import { readFile, writeFile } from "node:fs/promises";
import { resolve, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { isWithinDirectory } from "./path-containment.mjs";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "../.."),
  seen = new Set();
async function add(path) {
  path = resolve(path);
  if (!isWithinDirectory(root, path))
    throw Error("Shell asset escaped repository");
  if (seen.has(path)) return;
  seen.add(path);
  const text = await readFile(path, "utf8");
  if (/\.(mjs|js)$/.test(path))
    for (const match of text.matchAll(
      /(?:\bfrom\s*|\bimport\s*\(\s*|\bimport\s*)['"](\.[^'"]+)['"]/g,
    ))
      await add(resolve(dirname(path), match[1]));
  if (/\.html$/.test(path))
    for (const match of text.matchAll(
      /(?:src|href)="([^"#?:]+\.(?:mjs|js|css|webmanifest))"/g,
    ))
      await add(resolve(dirname(path), match[1]));
}
await add(resolve(root, "platform/learn/index.html"));
await add(resolve(root, "platform/learn/offline-preview.html"));
await add(resolve(root, "icons/icon-192.png"));
await add(resolve(root, "icons/apple-touch-icon.png"));
const assets = [];
for (const path of [...seen].sort()) {
  const bytes = await readFile(path);
  assets.push({
    path: relative(root, path).replaceAll("\\", "/"),
    bytes: bytes.length,
    sha256: createHash("sha256").update(bytes).digest("hex"),
  });
}
const version = createHash("sha256")
    .update(JSON.stringify(assets))
    .digest("hex")
    .slice(0, 16),
  output =
    "/* Generated by platform/tools/build-offline-shell.mjs. Public assets only. */\nself.CP_SHELL=" +
    JSON.stringify({ version, assets }, null, 2) +
    ";\n",
  target = resolve(root, "platform/learn/shell-manifest.js");
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== output)
    throw Error("Offline shell manifest is stale; rebuild it.");
} else await writeFile(target, output);
console.log(
  `${assets.length} public shell files; ${assets.reduce((n, a) => n + a.bytes, 0)} bytes; ${version}`,
);
