test("heading formatting and clipboard operations persist offline with distinct scores",async({page,context})=>{
  await page.goto("/platform/learn/offline-preview.html");
  await expect(page.getByRole("heading",{name:"Excel Study",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Study offline / Resume download",exact:true}).click();
  await expect(page.getByText(/Ready offline ·/)).toBeVisible({timeout:30000});
  await context.setOffline(true);
  await page.getByRole("button",{name:"Start heading formatting (reset worksheet)",exact:true}).click();
  const a1=page.locator('[data-cell="A1"]');
  await a1.click();
  for(const name of ["Bold","Fill Color","Borders"]) await page.getByRole("button",{name,exact:true}).click();
  await expect(a1).toHaveAttribute("data-practice-bold","true");
  await expect(a1).toHaveAttribute("data-practice-fill","true");
  await expect(a1).toHaveAttribute("data-practice-border","true");
  await page.getByRole("button",{name:"Submit formatting",exact:true}).click();
  await expect(page.getByText("Last formatting submission: 4 / 4",{exact:true})).toBeVisible();
  await expect(page.locator(".learn-save-status")).toContainText("Saved on this device");
  await page.reload();
  await page.getByRole("button",{name:"Resume saved study",exact:true}).click();
  await expect(a1).toHaveAttribute("data-practice-fill","true");
  await page.getByRole("button",{name:"Start clipboard practice (reset worksheet)",exact:true}).click();
  await page.locator('[data-cell="B2"]').click();
  await page.getByRole("button",{name:"Copy",exact:true}).click();
  await page.locator('[data-cell="B3"]').click();
  await page.getByRole("button",{name:"Paste",exact:true}).click();
  await expect(page.getByLabel(/^B3, /)).toHaveValue("12");
  await page.locator('[data-cell="B5"]').click();
  await page.getByLabel("Formula for B5",{exact:true}).fill("=SUM(B2:B4)");
  await page.getByRole("button",{name:"Apply formula",exact:true}).click();
  await expect(page.getByText("Last clipboard submission: 5 / 5",{exact:true})).toBeVisible();
  await expect(page.locator(".learn-save-status")).toContainText("Saved on this device");
  await page.reload();
  await page.getByRole("button",{name:"Resume saved study",exact:true}).click();
  await expect(page.getByText("Mode: Clipboard practice",{exact:true})).toBeVisible();
  await expect(page.getByText("Last formatting submission: 4 / 4",{exact:true})).toBeVisible();
  await expect(page.getByText("Last clipboard submission: 5 / 5",{exact:true})).toBeVisible();
  await context.setOffline(false);
  await expect(page.getByText("No changes waiting to sync.",{exact:true})).toBeVisible();
});
