"""Regenerate offline-assets.js after changing Python pages or bundled dependencies."""
from pathlib import Path
import hashlib, json, os, re
root = Path(__file__).resolve().parents[1]
repo = root.parents[1]
exclude = {'Temp', '_archive', 'New folder', '_build', 'sql', 'game_layer_impl', 'tools', 'tests'}
allowed = {'.html', '.js', '.css', '.json', '.png', '.svg', '.ico', '.jpg', '.webp', '.md', '.py', '.txt'}
files = {p for p in root.rglob('*') if p.is_file() and not (set(p.relative_to(root).parts) & exclude)
         and p.suffix in allowed and p.name not in {'offline-assets.js', 'sw.js', '_harness.html'}
         and '.test.' not in p.name and p.parent != root}
files.update(root / name for name in ['index.html', 'shelf.html', 'offline.html'])
# Follow local HTML/JS/CSS references, including CSS font URLs. Never fetch a CDN at build time.
pending = list(files)
while pending:
    p = pending.pop()
    if p.suffix not in {'.html', '.js', '.css'}: continue
    for ref in re.findall(r'''["'(]([^\s"'()<>]+)["')]''', p.read_text(errors='replace')):
        ref = ref.split('?')[0].split('#')[0]
        if not ref or len(ref) > 220 or ':' in ref or ref.startswith('/'): continue
        target = (p.parent / ref).resolve()
        if (target.is_relative_to(repo / '_lib') or target in {repo / 'reading-sync.js', repo / 'extras.js'}) and target.is_file() and target not in files and '_lib/pyodide/' not in str(target):
            files.add(target); pending.append(target)
core = {'pyodide.js', 'pyodide.asm.js', 'pyodide.asm.wasm', 'python_stdlib.zip', 'pyodide-lock.json'}
runtime = repo / '_lib/pyodide'
# Pillow supports the existing image exercises; package dependencies are self-contained here.
core.update(p.name for p in runtime.glob('pillow-*.whl'))
files.update(runtime / name for name in core)
extra = {p for p in runtime.iterdir() if p.suffix in {'.whl', '.zip'} and p.name not in core}
def entry(p):
    data = p.read_bytes()
    return {'url': os.path.relpath(p, root).replace(os.sep, '/'), 'bytes': len(data), 'revision': hashlib.sha256(data).hexdigest()}
def entries(items): return [entry(p) for p in sorted(items)]
manifest = {'basic': entries(files), 'science': entries(extra)}
(root / 'offline-assets.js').write_text('/* Generated by tools/build-offline.py. Do not edit by hand. */\nself.CP_OFFLINE_ASSETS = ' + json.dumps(manifest, indent=2) + ';\n')
for k, v in manifest.items(): print(k, len(v), 'files,', round(sum(a['bytes'] for a in v)/1e6, 1), 'MB')
