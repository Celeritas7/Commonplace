"""Build the SQL pack from local dependencies. Run --check in CI after ANY shared edit."""
from pathlib import Path
import hashlib, json, os, re, sys
root = Path(__file__).resolve().parents[1]
repo = root.parents[1]
repair = (root / 'offline.html').read_text().replace('<title>Study offline · SQL</title>', '<title>Repair offline setup · SQL</title>').replace('<script src="lib/offline-manager.js"></script>', '<script>\n' + (root/'lib/offline-manager.js').read_text() + '\n</script>')
if '--check' not in sys.argv: (root/'offline-repair.html').write_text(repair)
elif (root/'offline-repair.html').read_text() != repair: sys.exit('SQL standalone repair page is stale. Run build-offline.py.')
excluded = {'tools', 'tests', 'supabase'}
files = {p for p in root.rglob('*') if p.is_file() and not set(p.relative_to(root).parts) & excluded
         and p.suffix in {'.html','.js','.css','.json','.webmanifest','.png','.svg'}
         and '.template.' not in p.name and p.name not in {'sw.js','offline-assets.js'}}
# Dynamic SQL runtime and auth dependencies are explicitly included.
files.update((repo / '_lib/sqljs').glob('*'))
files.update([repo / '_lib/supabase.js', repo / 'extras.js'])
pending = list(files)
while pending:
    p = pending.pop()
    if p.suffix not in {'.html','.js','.css','.json','.webmanifest'}: continue
    for ref in re.findall(r'''["'(]([^\s"'()<>]+)["')]''', p.read_text(errors='replace')):
        ref = ref.split('?')[0].split('#')[0]
        if not ref or len(ref)>220 or ':' in ref or ref.startswith('/'): continue
        target = (p.parent / ref).resolve()
        if target.name not in {'sw.js','offline-assets.js'} and target.is_relative_to(repo) and target.is_file() and target not in files and target.suffix in {'.js','.css','.woff','.woff2','.png','.svg','.ico'}:
            files.add(target); pending.append(target)
assets = []
for p in sorted(files):
    data = p.read_bytes()
    assets.append({'url':os.path.relpath(p,root).replace(os.sep,'/'),'bytes':len(data),'revision':hashlib.sha256(data).hexdigest()})
text = '/* Generated by tools/build-offline.py; CI checks shared dependencies too. */\nself.SQL_OFFLINE_ASSETS = '+json.dumps(assets,indent=2)+';\n'
out = root/'offline-assets.js'
if '--check' in sys.argv:
    if not out.exists() or out.read_text()!=text:
        sys.exit('SQL offline manifest is stale. Run python3 Coding/sql/tools/build-offline.py and commit it with the changed files.')
else: out.write_text(text)
print(f'{len(assets)} files, {sum(a["bytes"] for a in assets):,} bytes')
