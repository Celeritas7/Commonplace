"""Generate a content-addressed C/C++ pack; --check is suitable for CI.
Follow transitive shared dependencies, so a gate/font/editor change changes its hash.
No network is used. Archives and private/cloud records are never packaged.
"""
from pathlib import Path
import hashlib, json, os, re, sys
root = Path(__file__).resolve().parents[1]
repo = root.parents[1]
exclude = {'_archive', '_review', 'Temo', 'practice_import', 'tests', 'tools'}
allowed = {'.html', '.js', '.css', '.json', '.png', '.svg', '.ico', '.jpg', '.webp', '.woff', '.woff2'}
files = {p.resolve() for p in root.rglob('*') if p.is_file()
         and not set(p.relative_to(root).parts) & exclude and p.suffix in allowed
         and p.name not in {'offline-assets.js', 'sw.js'}}
# Runtime URL construction in progress-backup.js is not a literal relative URL.
files.update(repo / name for name in ['extras.js', '_lib/autoscroll.js', '_lib/quiz/quiz.js', '_lib/supabase.js'])
pending = list(files)
while pending:
    p = pending.pop()
    if p.suffix not in {'.html', '.js', '.css', '.json'}: continue
    for ref in re.findall(r'''["'(]([^\s"'()<>]+)["')]''', p.read_text(errors='replace')):
        ref = ref.split('?')[0].split('#')[0]
        if not ref or len(ref)>220 or ':' in ref or ref.startswith('/'): continue
        target = (p.parent / ref).resolve()
        if not target.is_relative_to(repo): continue
        if target.is_file() and (target.is_relative_to(repo / '_lib') or target.name in {'reading-sync.js', 'extras.js'}):
            if target not in files:
                files.add(target); pending.append(target)
# gate.js dynamically loads its sibling SDK; reading-sync does likewise.
files.add(repo / '_lib/supabase.js')
def entry(p):
    data=p.read_bytes()
    return {'url': os.path.relpath(p,root).replace(os.sep,'/'), 'bytes': len(data), 'revision': hashlib.sha256(data).hexdigest()}
assets=[entry(p) for p in sorted(files)]
version=hashlib.sha256(json.dumps(assets,sort_keys=True).encode()).hexdigest()[:16]
result='/* Generated by tools/build-offline.py */\nself.CPP_PACK = '+json.dumps({'version':version,'assets':assets},indent=2)+';\n'
path=root/'offline-assets.js'
if '--check' in sys.argv:
    if not path.exists() or path.read_text()!=result:
        sys.exit('C/C++ offline manifest is stale. Run python Coding/c_and_cpp_study/tools/build-offline.py')
else: path.write_text(result)
print(f'C/C++: {len(assets)} files, {sum(a["bytes"] for a in assets):,} bytes; version {version}')
